# Mochi's English echoes: the English said in katakana by the same voice (春日部つむぎ),
# so it comes out as English with a Japanese accent. Also makes any new Japanese line ("new": true).
# Longer phrases (3+ words) are softened: the extra vowel Japanese adds after a final consonant
# (グッ"ド" → good, イッ"ト" → it) is whispered instead of voiced, so the English stays clear.
# Loudness and tone go through the same chain as Mochi's Japanese lines (tools/normalize.py).
import json, subprocess, re, os, sys
from voicevox_core.blocking import Onnxruntime, OpenJtalk, Synthesizer, VoiceModelFile
D = '/home/claude/dl'; OUT = '/home/claude/hiragana-quest/audio/voice'
ort = Onnxruntime.load_once(filename=f'{D}/voicevox_onnxruntime-linux-x64-1.17.3/lib/libvoicevox_onnxruntime.so.1.17.3')
syn = Synthesizer(ort, OpenJtalk(f'{D}/open_jtalk_dic_utf_8-1.11'))
with VoiceModelFile.open(f'{D}/0.vvm') as m: syn.load_voice_model(m)
MOCHI = 8
CHAIN = 'highpass=f=110,equalizer=f=2800:t=q:w=1.2:g=3,acompressor=threshold=-28dB:ratio=4:attack=2:release=80:makeup=2'
SOFT_C = {'k', 'g', 't', 'd', 's', 'z', 'f', 'b', 'p', 'ts', 'sh', 'ch'}
TARGET_MEAN = -13.0

def vol(path, chain=None):
    af = (chain + ',' if chain else '') + 'volumedetect'
    o = subprocess.run(['ffmpeg', '-hide_banner', '-nostats', '-i', path, '-af', af, '-f', 'null', '-'], capture_output=True, text=True).stderr
    return float(re.search(r'mean_volume: (-?[\d.]+)', o).group(1)), float(re.search(r'max_volume: (-?[\d.]+)', o).group(1))

def synth(text, soften):
    q = syn.create_audio_query(text, MOCHI)
    for ph in q.accent_phrases[:-1]:
        ph.pause_mora = None                      # words flow together, no gap after each one
    if soften:
        for ph in q.accent_phrases:
            m = ph.moras[-1]
            if m.consonant in SOFT_C and m.vowel in ('u', 'o'):
                m.vowel = m.vowel.upper(); m.vowel_length *= 0.7; m.pitch = 0.0
    q.speed_scale = 1.0; q.intonation_scale = 1.3; q.volume_scale = 1.4
    return syn.synthesis(q, MOCHI), q.kana

def finish(wav, out):
    open('/tmp/me.wav', 'wb').write(wav)
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', '/tmp/me.wav', '-af',
      'silenceremove=start_periods=1:start_threshold=-50dB,areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse,apad=pad_dur=0.08',
      '/tmp/me_t.wav'], check=True)
    mean, peak = vol('/tmp/me_t.wav', CHAIN)
    gain = min(TARGET_MEAN - mean, -1.2 - peak + 4.0)
    subprocess.run(['ffmpeg', '-y', '-loglevel', 'error', '-i', '/tmp/me_t.wav', '-af',
      f'{CHAIN},volume={gain:.2f}dB,alimiter=limit=0.89:level=false', '-ac', '1', '-ar', '24000', '-b:a', '64k', out], check=True)
    return vol(out)

lines = json.load(open('/home/claude/tools/mochi_lines.json'))
only = set(sys.argv[1].split(',')) if len(sys.argv) > 1 else None
os.makedirs(f'{OUT}/en', exist_ok=True)
for L in lines:
    if only and L['id'] not in only: continue
    if L.get('new'):
        q = syn.create_audio_query(L['ja'], MOCHI); q.intonation_scale = 1.3; q.volume_scale = 1.4
        print(L['id'], 'ja', finish(syn.synthesis(q, MOCHI), f"{OUT}/{L['id']}.mp3"))
    soften = len(L['kk'].split()) >= 3
    wav, k = synth(L['kk'], soften)
    print(L['id'], 'en', k, 'soft' if soften else '', finish(wav, f"{OUT}/en/{L['id']}.mp3"))
# The game's copy of the line texts
js = 'export const LINES = ' + json.dumps({L['id']: {'ja': L['ja'], 'en': L['en']} for L in lines}, ensure_ascii=False) + ';\n'
open('/home/claude/hiragana-quest/js/lines.js', 'w').write('// Generated by tools/gen_mochi_english.py: what Mochi says, in Japanese and English.\n' + js)
